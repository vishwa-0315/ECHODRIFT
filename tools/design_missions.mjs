/**
 * Mission design tool: computes starting states from real ephemerides and
 * real mission events, then writes content/mission_design.json.
 * Run: node tools/design_missions.mjs   (takes ~20 s)
 *
 *  - Apollo 13: a free-return trajectory through the real 15 Apr 1970 lunar
 *    flyby (254 km) that re-enters Earth's atmosphere at −6.5°, then the
 *    "hybrid" trajectory the crew was really on (perilune ≈ 110–120 km,
 *    misses Earth) at the moment of the explosion.
 *  - Voyager 2: the 1979 cruise state that flies past Jupiter at ~642,000 km
 *    on 9 Jul 1979 and reaches Saturn at ~161,000 km on 26 Aug 1981.
 *  - Aditya-L1: a planar Lyapunov orbit about Sun–Earth L1 (period ≈ 178 d),
 *    the 2D counterpart of Aditya's real halo orbit, as a reference table.
 */
import { writeFileSync } from 'node:fs';
import { createDopri } from '../src/core/ode.js';
import { createOrbitalSim } from '../src/core/orbitalsim.js';
import { helioState, geoState } from '../src/core/ephem.js';
import { lambert } from '../src/core/orbit.js';
import { MU, RADIUS, DAY, AU } from '../src/core/constants.js';
import { nelderMead, solve1D } from '../src/core/targeting.js';

const out = { _generated: new Date().toISOString(), _note: 'Generated by tools/design_missions.mjs from real ephemerides. Do not edit by hand.' };

/* ---------------- Apollo 13 ---------------- */
{
  const Rm = RADIUS.moon;
  const tPer = '1970-04-15T00:21:00Z';
  const base = { epoch: '1970-04-13T00:00:00Z', span: 8 * DAY, central: 'earth', perturbers: ['moon', 'sun'], ship: { wetMass: 44000, dryMass: 35800, engine: { thrust: 45040, isp: 311 } }, entryInterface: { body: 'earth', altitude: 121920, stop: true } };
  const explosion = '1970-04-14T03:08:00Z';
  const tP = (Date.parse(tPer) - Date.parse(base.epoch)) / 1000;
  const tX = (Date.parse(explosion) - Date.parse(base.epoch)) / 1000;
  const moon = geoState('moon', new Date(tPer));
  const build = ([phiDeg, vrel]) => {
    const phi = (phiDeg * Math.PI) / 180;
    const r = Rm + 254e3;
    const sim = createOrbitalSim({ ...base, state: { x: 0, y: 0, vx: 0, vy: 0 } });
    sim.t = tP;
    sim.y = [moon.x + r * Math.cos(phi), moon.y + r * Math.sin(phi), moon.vx + vrel * Math.sin(phi), moon.vy - vrel * Math.cos(phi), 44000];
    return sim;
  };
  const cost = (p) => {
    const pr = build(p).predict(3.2 * DAY, 3600);
    return pr.entry ? (pr.entry.gamma + 6.5) ** 2 : 100 + ((pr.closest.earth.d - RADIUS.earth) / 1e6) ** 2;
  };
  let best = null;
  for (let phi = 0; phi < 360; phi += 15) for (const v of [2300, 2450, 2600]) {
    const c = cost([phi, v]);
    if (!best || c < best.c) best = { c, p: [phi, v] };
  }
  const r = nelderMead(cost, best.p, [5, 30], { iters: 120 });
  const s = build(r.x);
  s.coast(tX - tP);
  const free = s.y.slice(0, 4);
  // the hybrid (non-free-return) trajectory: 3 m/s slower along the velocity
  const v = Math.hypot(free[2], free[3]);
  const hybrid = [free[0], free[1], free[2] - (3 * free[2]) / v, free[3] - (3 * free[3]) / v];
  out.apollo13 = { epoch: explosion, freeReturn: free, state: hybrid };
  console.log('Apollo 13: free-return found, entry γ target −6.5°');
}

/* ---------------- Voyager 2 ---------------- */
{
  const tJ = Date.parse('1979-07-09T22:29:00Z');
  const tS = Date.parse('1981-08-26T03:24:00Z');
  const epoch = '1979-03-01T00:00:00Z';
  const tE = Date.parse(epoch);
  const J = helioState('jupiter', new Date(tJ));
  let vinfOut, vinf;
  const setTarget = (sh) => {
    const t2 = tS + sh * DAY * 1000;
    const S2 = helioState('saturn', new Date(t2));
    const o = lambert([J.x, J.y], [S2.x, S2.y], (t2 - tJ) / 1000, MU.sun);
    vinfOut = [o.v1[0] - J.vx, o.v1[1] - J.vy];
    vinf = Math.hypot(...vinfOut);
  };
  const def0 = { epoch, span: 3 * 365 * DAY, central: 'sun', perturbers: ['jupiter', 'saturn'], ship: { wetMass: 722, dryMass: 640, engine: { thrust: 890, isp: 220 } } };
  const build = ([rpKm, rot]) => {
    const rp = rpKm * 1e3;
    const mu = MU.jupiter;
    const vp = Math.sqrt(vinf * vinf + (2 * mu) / rp);
    const half = Math.asin(1 / (1 + (rp * vinf * vinf) / mu));
    const ua = Math.atan2(vinfOut[1], vinfOut[0]) + rot;
    const sgn = -1;
    const angP = ua - sgn * (Math.PI / 2 + half);
    const sim = createOrbitalSim({ ...def0, state: { x: 0, y: 0, vx: 0, vy: 0 } });
    sim.t = (tJ - tE) / 1000;
    sim.y = [J.x + rp * Math.cos(angP), J.y + rp * Math.sin(angP), J.vx - Math.sin(angP) * sgn * vp, J.vy + Math.cos(angP) * sgn * vp, 722];
    sim.coast(-sim.t);
    return sim;
  };
  const evalP = (p) => {
    setTarget(p[2]);
    const s = build(p);
    const pr = s.predict((tS - tE) / 1000 + 60 * DAY, 2 * DAY);
    return { s, pr };
  };
  const cost = (p) => {
    const { pr } = evalP(p);
    const dt = (tE + pr.closest.saturn.t * 1000 - tS) / 86400000;
    return ((pr.closest.saturn.d - 161000e3) / 1e8) ** 2 + ((p[0] - 641500) / 2e5) ** 2 * 0.01 + (dt / 3) ** 2;
  };
  const res = nelderMead(cost, [641500, 0.003, 15], [20000, 0.002, 5], { iters: 150 });
  const { s, pr } = evalP(res.x);
  const good = s.y.slice(0, 4);
  // starting state used in the game: before the final course correction (misses Saturn)
  const v = Math.hypot(good[2], good[3]);
  const off = [good[0], good[1], good[2] + (0.6 * -good[3]) / v, good[3] + (0.6 * good[2]) / v];
  out.voyager2 = { epoch, onTarget: good, state: off, jupiterKm: pr.closest.jupiter.d / 1e3, saturnKm: pr.closest.saturn.d / 1e3 };
  console.log(`Voyager 2: Jupiter ${(pr.closest.jupiter.d / 1e3).toFixed(0)} km, Saturn ${(pr.closest.saturn.d / 1e3).toFixed(0)} km`);
}

/* ---------------- Aditya-L1 ---------------- */
{
  const mu = (MU.earth + MU.moon) / (MU.sun + MU.earth + MU.moon);
  const f = (t, y, d) => {
    const [x, yy, vx, vy] = y;
    const r1 = Math.hypot(x + mu, yy);
    const r2 = Math.hypot(x - 1 + mu, yy);
    d[0] = vx;
    d[1] = vy;
    d[2] = 2 * vy + x - ((1 - mu) * (x + mu)) / r1 ** 3 - (mu * (x - 1 + mu)) / r2 ** 3;
    d[3] = -2 * vx + yy - ((1 - mu) * yy) / r1 ** 3 - (mu * yy) / r2 ** 3;
  };
  const gx = (x) => x - ((1 - mu) * (x + mu)) / Math.abs(x + mu) ** 3 - (mu * (x - 1 + mu)) / Math.abs(x - 1 + mu) ** 3;
  const L1 = solve1D(gx, 0.98, 0.999, { tol: 1e-14 });
  const x0 = L1 - 166000e3 / AU;
  const cross = (vy0) => {
    const y = [x0, 0, 0, vy0];
    let prev = y.slice();
    let c = null;
    createDopri(f, 4, { rtol: 1e-12, atol: 1e-14, h0: 1e-4 }).advance(0, y, 4, (tt, yy) => {
      if (tt > 0.01 && prev[1] * yy[1] < 0) {
        c = { t: tt, vx: yy[2] };
        return true;
      }
      prev = yy.slice();
      return false;
    });
    return c;
  };
  let br = null;
  let pv = null, pg = null;
  for (let v = 0.001; v <= 0.03; v += 0.0005) {
    const g = cross(v)?.vx;
    if (pg != null && g != null && pg * g < 0) {
      br = [pv, v];
      break;
    }
    pv = v;
    pg = g;
  }
  const vy0 = solve1D((v) => cross(v)?.vx ?? NaN, br[0], br[1], { tol: 1e-13 });
  const Tnd = 2 * cross(vy0).t;
  const table = [];
  const y = [x0, 0, 0, vy0];
  const ig = createDopri(f, 4, { rtol: 1e-12, atol: 1e-14, h0: 1e-4 });
  for (let i = 0; i <= 360; i++) {
    table.push([Math.round((y[0] - (1 - mu)) * AU), Math.round(y[1] * AU)]); // m, relative to Earth–Moon barycentre (≈ Earth)
    ig.advance(0, y, Tnd / 360);
  }
  const periodDays = (Tnd / (2 * Math.PI)) * 365.25636;
  out.aditya = { epoch: '2024-01-06T10:30:00Z', L1km: ((1 - mu - L1) * AU) / 1e3, x0, vy0, mu, periodDays, reference: table };
  console.log(`Aditya-L1: L1 at ${((1 - mu - L1) * AU / 1e3).toFixed(0)} km, reference period ${periodDays.toFixed(1)} d`);
}

writeFileSync(new URL('../content/mission_design.json', import.meta.url), JSON.stringify(out));
console.log('✓ wrote content/mission_design.json');
